/*
 * ==============================================================
 *  หัวข้อ    : Pointer
 *  ข้อที่    : 9    |    ระดับ : ประยุกต์
 *  ชื่อโจทย์ : ไล่โค้ด (Trace) หาผลลัพธ์
 * ==============================================================
 *  [โจทย์]
 *    ข้อนี้ไม่ต้องเขียนโปรแกรม ให้อ่านโค้ดด้านล่าง
 *    แล้วเขียนผลลัพธ์ที่คาดว่าจะได้ทั้ง 6 บรรทัดลงกระดาษก่อน
 *    จากนั้นจึง compile และ run เพื่อตรวจคำตอบของตัวเอง
 *
 *  [Input]
 *    ไม่มี
 *
 *  [Output]
 *    6 บรรทัด (หาเองด้วยการไล่โค้ด)
 *
 *  [ข้อกำหนด / คำใบ้]
 *    วาดรูปกล่องหน่วยความจำของ a[0]..a[4] และลูกศรของ p, q ประกอบการไล่
 *
 * ==============================================================
 */
#include <stdio.h>

int main(void)
{
    int a[5] = {10, 20, 30, 40, 50};
    int *p = a;
    int *q = &a[3];

    printf("%d\n", *p);
    printf("%d\n", *(p + 2));
    p++;
    printf("%d\n", *p);
    printf("%d\n", *q - *p);
    printf("%d\n", (int)(q - p));
    *q = *p + 5;
    printf("%d\n", a[3]);

    return 0;
}
