/*
 * ==============================================================
 *  หัวข้อ    : Array
 *  ข้อที่    : 2    |    ระดับ : ง่าย
 *  ชื่อโจทย์ : กลับลำดับสมาชิกในอาร์เรย์
 * ==============================================================
 *  [โจทย์]
 *    รับจำนวนเต็ม n ตัว แล้วกลับลำดับสมาชิก "ภายในอาร์เรย์เดิม"
 *    (สลับค่าจริง ๆ ไม่ใช่แค่พิมพ์ย้อนหลัง) จากนั้นพิมพ์อาร์เรย์
 *
 *  [Input]
 *    บรรทัดแรก: n (1 <= n <= 100)
 *    บรรทัดที่สอง: จำนวนเต็ม n ตัว
 *
 *  [Output]
 *    สมาชิกหลังกลับลำดับ คั่นด้วยช่องว่าง 1 ช่อง
 *
 *  [Test case 1]
 *   Input:
 *      5
 *      1 2 3 4 5
 *   Output:
 *      5 4 3 2 1
 *
 *  [Test case 2]
 *   Input:
 *      4
 *      10 20 30 40
 *   Output:
 *      40 30 20 10
 *
 *  [Test case 3]
 *   Input:
 *      1
 *      7
 *   Output:
 *      7
 *
 *  [ข้อกำหนด / คำใบ้]
 *    ใช้ดัชนี 2 ตัว (หัว-ท้าย) วิ่งเข้าหากัน และตัวแปร temp ในการสลับ
 *
 * ==============================================================
 */
#include <stdio.h>
#include <stdlib.h>
int main(void)
{
    int n, *numPtr;
    printf("Input:\n");
    scanf("%d", &n);
    numPtr = malloc(n * sizeof(int));
    for (int i = 0; i < n; i++)
    {
        scanf(" %d", &numPtr[i]);
    }
    for (int i = 1; i <= (int)(n / 2); i++)
    {
        int temp = numPtr[i - 1];
        numPtr[i - 1] = numPtr[n - i];
        numPtr[n - i] = temp;
    }
    printf("\nOutput:\n");
    for (int i = 0; i < n; i++)
    {
        printf("%d ", numPtr[i]);
    }
    return 0;
}
